const assert = require('node:assert/strict');
const {update} = require('../js/invoice-payment-state.js');
const base = [{id:'one',total:100,status:'UNPAID'},{id:'two',total:200,status:'PAID'}];
let s=update(base,'one',{type:'CREATE'},1000,'PAY-1');
assert.equal(base[0].paymentAttempts,undefined);
assert.equal(update(s,'one',{type:'CREATE'},1001,'PAY-2')[0].paymentAttempts.length,1);
s=update(s,'one',{type:'SUBMIT',id:'PAY-1'},1002);
assert.equal(s[0].status,'UNPAID');
s=update(s,'one',{type:'RESOLVE',id:'PAY-1',result:'FAILED'},1003);
assert.equal(s[0].status,'UNPAID');
s=update(s,'one',{type:'CREATE'},1004,'PAY-2');
assert.equal(s[0].paymentAttempts.length,2);
s=update(s,'one',{type:'RESOLVE',id:'PAY-2',result:'SUCCESS'},1005);
assert.equal(s[0].status,'PAID');
assert.equal(s[0].paymentReference,'PAY-2');
assert.throws(()=>update(s,'one',{type:'CREATE'},1006,'PAY-3'));
assert.deepEqual(update(s,'one',{type:'RESOLVE',id:'PAY-2',result:'FAILED'},1007),s);
let expired=update(base,'one',{type:'CREATE'},1000,'PAY-X');
expired=update(JSON.parse(JSON.stringify(expired)),'one',{type:'RESOLVE',id:'PAY-X',result:'SUCCESS'},901000);
assert.equal(expired[0].paymentAttempts[0].status,'EXPIRED');
assert.equal(expired[0].status,'UNPAID');
assert.throws(()=>update(base,'two',{type:'CREATE'},1000,'PAY-Y'));
console.log('PASS: create, duplicate clicks, submit, failure, retry, success, paid guard, terminal state, reload and expiration');
